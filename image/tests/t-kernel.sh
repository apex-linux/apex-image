#!/bin/sh
. "$(dirname -- "$0")/lib.sh"
. "$TESTS_DIR/pair-root.sh"

command -v python3 >/dev/null 2>&1 || skip_all "python3 not found"

pair_root fedora fedora
check kernel "$R"
expect_rc "Fedora's kernel: passes" 0
expect_out "nouveau blacklisted by apex-dgpu.conf" '^PASS kernel: nouveau blacklisted by /usr/lib/modprobe.d/apex-dgpu.conf$'
expect_out "no NVIDIA module in the initramfs" '^PASS kernel: no NVIDIA module in the initramfs$'
expect_no_out "and no pair assertion" 'pair'

pair_root fedora-nvidia fedora
printf -- '-rw-r--r--   1 root root 0 Jan  1 00:00 usr/lib/modules/%s/extra/nvidia/nvidia.ko.xz\n' "$FEDORA_KVER" \
    >>"$R/usr/lib/modules/$FEDORA_KVER/initramfs.img"
check kernel "$R"
expect_rc "an NVIDIA module in the initramfs: fails" 1
expect_out "and says why" '^FAIL kernel: an NVIDIA module is in the initramfs'

pair_root pair pair
check kernel "$R"
expect_rc "the pair: passes" 0
expect_out "the locked kernel" "^PASS kernel: the pair's kernel: kernel-cachyos-core-0:$KVER\$"
expect_out "Fedora's kernel-headers is no kernel package" "^PASS kernel: no package of Fedora's kernel\$"
expect_out "the config" '^PASS kernel: the kernel config has every line of config-required\.txt$'
expect_out "the kernel arguments" '^PASS kernel: kernel argument module\.sig_enforce=1$'
expect_out "nouveau blocked by module_blacklist" '^PASS kernel: nouveau blacklisted by /usr/lib/bootc/kargs\.d/20-apex-pair\.toml \(kernel argument\)$'
expect_out "every module signed by the build's key" "^PASS kernel: all 7 modules are signed by the build's own key \\($SIGNER\\)\$"

pair_root degraded degraded
check kernel "$R"
expect_rc "the pair's kernel without its NVIDIA set: passes" 0
expect_out "with its 2 modules" "^PASS kernel: all 2 modules are signed"

pair_root pair-fedora pair
rpmdb_add "$R" kernel-core '{"evr": "7.2.9-200.fc45", "sourcerpm": "kernel-7.2.9-200.fc45.src.rpm"}'
check kernel "$R"
expect_rc "Fedora's kernel next to the pair's: fails" 1
expect_out "and names it" "^FAIL kernel: packages of Fedora's kernel next to the pair's: kernel-core\$"

pair_root pair-relock pair
sed -i 's/kernel-cachyos-core-0:7\.3\.0-4/kernel-cachyos-core-0:7.3.1-1/' "$R/usr/share/apex/rpms.lock"
check kernel "$R"
expect_rc "a kernel other than the locked one: fails" 1
expect_out "and names both" "^FAIL kernel: kernel-cachyos-core is kernel-cachyos-core-0:$KVER, but rpms\\.lock locks kernel-cachyos-core-0:7\\.3\\.1-1"

pair_root pair-config pair
sed -i '/^CONFIG_DEBUG_INFO_BTF=y$/d' "$R/usr/lib/modules/$KVER/config"
check kernel "$R"
expect_rc "a config without BTF: fails" 1
expect_out "and names the line" '^FAIL kernel: the kernel config lacks: CONFIG_DEBUG_INFO_BTF=y$'

pair_root pair-norequired pair
rm "$RPMS/pair/config-required.txt"
check kernel "$R"
expect_rc "no config-required.txt: fails" 1

pair_root pair-kargs pair
sed -i '/"module.sig_enforce=1",/d' "$R/usr/lib/bootc/kargs.d/20-apex-pair.toml"
check kernel "$R"
expect_rc "no module.sig_enforce=1: fails" 1
expect_out "and names it" '^FAIL kernel: kernel argument module\.sig_enforce=1 missing'

pair_root pair-unsigned pair
module "$R/usr/lib/modules/$KVER/kernel/fs/overlay/overlay.ko.xz" "$KVER" ""
check kernel "$R"
expect_rc "an unsigned module: fails" 1
expect_out "and counts it" '^FAIL kernel: 1 of 8 modules carry no signature$'

pair_root pair-signers pair
module "$R/usr/lib/modules/$KVER/kernel/fs/overlay/overlay.ko.xz" "$KVER" "Build time autogenerated kernel key"
check kernel "$R"
expect_rc "a module signed by another key: fails" 1
expect_out "and names both" '^FAIL kernel: the modules carry more than one signer: Apex kernel .*,Build time autogenerated kernel key$'

done_testing
